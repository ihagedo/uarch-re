#!/bin/bash
# One-time Chipyard setup for BOOM RTL under Verilator, no sudo: ~30-40 min, ~15 GB under /var/tmp/$USER.
#   validation/boom/setup.sh
# Chipyard's lean conda env brings its own Verilator (not /usr/bin/verilator) and riscv64-unknown-elf.
set -e
USER=${USER:-$(id -un)}
CPUS=${UARCHRE_GEM5_CPUS:-4-19}
[ -z "$UARCHRE_PINNED" ] && exec env UARCHRE_PINNED=1 taskset -c "$CPUS" "$0" "$@"
CHIPYARD=${CHIPYARD:-/var/tmp/$USER/chipyard}
MINIFORGE=${MINIFORGE:-/var/tmp/$USER/miniforge3}
TAG=${CHIPYARD_TAG:-1.14.0}
LOG=${UARCHRE_SCRATCH:-/var/tmp/$USER/uarch-re}/logs/boom
mkdir -p "$LOG"

if ! command -v conda >/dev/null && [ ! -x "$MINIFORGE/bin/conda" ]; then
  curl -sSL -o /var/tmp/$USER/Miniforge3-Linux-x86_64.sh \
    https://github.com/conda-forge/miniforge/releases/latest/download/Miniforge3-Linux-x86_64.sh
  bash /var/tmp/$USER/Miniforge3-Linux-x86_64.sh -b -p "$MINIFORGE"
fi
CONDA_SH=$( [ -x "$MINIFORGE/bin/conda" ] && echo "$MINIFORGE/etc/profile.d/conda.sh" || echo "$(conda info --base)/etc/profile.d/conda.sh")
source "$CONDA_SH"

[ -d "$CHIPYARD" ] || git clone --branch "$TAG" --depth 1 https://github.com/ucb-bar/chipyard "$CHIPYARD"
cd "$CHIPYARD"

# build-setup step 1 by hand: build-setup.sh would regenerate the lockfile for the host glibc and can fail
if [ ! -d .conda-env ]; then
  conda create -y -p "$CHIPYARD/.conda-lock-env" -c conda-forge conda-lock=2.5.7
  conda activate "$CHIPYARD/.conda-lock-env"
  conda-lock install --conda "$CONDA_EXE" -p "$CHIPYARD/.conda-env" \
    conda-reqs/conda-lock-reqs/conda-requirements-riscv-tools-linux-64-lean.conda-lock.yml
  conda deactivate
fi

./scripts/init-submodules-no-riscv-tools.sh > "$LOG/setup-submodules.log" 2>&1

source scripts/utils.sh
common_setup
replace_content env.sh build-setup-conda "# line auto-generated by uarch-re validation/boom/setup.sh
source $CONDA_SH
conda activate $CHIPYARD/.conda-env
source $CHIPYARD/scripts/fix-open-files.sh"
conda activate "$CHIPYARD/.conda-env"
export MAKEFLAGS=-j${JOBS:-4}
# steps 3 (spike, pk, riscv-tests, libgloss, DRAMSim2), 5 (sbt precompile) and 10 (CIRCT)
./build-setup.sh riscv-tools -s 1 -s 2 -s 4 -s 6 -s 7 -s 8 -s 9 -s 11 > "$LOG/setup-rest.log" 2>&1
echo "Chipyard ready: source $CHIPYARD/env.sh"
