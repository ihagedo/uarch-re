class TestOnset(unittest.TestCase):
    def test_step_onset(self):
        # LRU ramp from C = 32 (lower plateau 3) to the upper plateau 17
        xs = [28, 30, 32, 33, 34, 36, 40]
        ys = [3, 3, 3.1, 5, 8, 17, 17]
        self.assertEqual(M.plateau_onset(xs, ys, 3, 17, frac=0.1), (32, 33))

    def test_unsorted_and_no_rise(self):
        self.assertEqual(M.plateau_onset([3, 1, 2], [1, 1, 1], 1, 10), (3, None))

    def test_dip_after_rise_ignored(self):
        # a later point below threshold does not move the onset
        xs = [1, 2, 3, 4]
        ys = [1, 9, 1.2, 9]
        self.assertEqual(M.plateau_onset(xs, ys, 1, 10, frac=0.1), (1, 2))


class TestParse(unittest.TestCase):
    def test_parse_runs(self):
        out = (
            "tsc_hz 2688000000\nclock_ratio 0.6812\n"
            "R lat 4096 0 3.0000\nR lat 4096 1 3.5000\nR mlp 8 0 170.25\n"
        )
        runs, sc = M.parse_runs(out)
        self.assertEqual(runs["lat"][4096], [3.0, 3.5])
        self.assertEqual(runs["mlp"][8], [170.25])
        self.assertAlmostEqual(sc["clock_ratio"], 0.6812)
        self.assertEqual(sc["tsc_hz"], 2688000000.0)


class TestSource(unittest.TestCase):
    def test_both_isas_generate(self):
        for isa in ("riscv64", "x86_64"):
            src = M.chase_source(isa)
            self.assertNotIn("@", src.split("generated by")[1].split("int main")[0].replace("@NPMAX", ""))
            self.assertIn("build_chain", src)  # the window template's own builder

    def test_template_chain_matches_isa_base(self):
        from uarchre.backends.isa_base import C_TEMPLATE

        body = M.template_chain_c()
        self.assertTrue(body.startswith("static void *build_chain("))
        self.assertIn(body.replace("{", "{{").replace("}", "}}"), C_TEMPLATE)

    def test_mlp_register_budget(self):
        # 31 FP + 24 int chain registers, s11 counter, t0 / f31 scratch: no overlap
        self.assertEqual(M.MLP_KMAX, 55)
        self.assertNotIn("s11", M.MLP_INT_REGS)
        self.assertNotIn("t0", M.MLP_INT_REGS)
        self.assertEqual(len(set(M.MLP_INT_REGS)), len(M.MLP_INT_REGS))
        src = M.chase_source("riscv64")
        self.assertIn("static void mlp_55(", src)
        self.assertNotIn("static void mlp_56(", src)

    def test_baremetal_source(self):
        src = M.tlb_baremetal_source([4, 64, 128], nloads=256, reps=2)
        self.assertIn("static const uint32_t PLIST[] = { 4, 64, 128 };", src)
        self.assertIn("csrw satp", src)
        with self.assertRaises(ValueError):
            M.tlb_baremetal_source([M.BM_NPMAX + 1])


class TestMoreSources(unittest.TestCase):
    def test_itlb_source(self):
        src = M.tlb_baremetal_source([4, 8], nloads=64, reps=1, itlb=True)
        self.assertIn("#define ITLB 1", src)
        self.assertIn("write_stub", src)
        self.assertIn("#define ITLB 0", M.tlb_baremetal_source([4], itlb=False))

    def test_memdep_source(self):
        src = M.memdep_source([4, 130])
        self.assertIn("static void mda_130(", src)
        self.assertIn(".option norvc", src)
        # blocks past 127 use the second base register (16 B slots, imm12 reach)
        self.assertIn("sd a0, 32(t1)", src)
        self.assertIn("divu t1, s3, s2", src)
        self.assertIn("ld a1, 0(s4)", M.memdep_source([4], alias=False))


class TestMLPAnalysis(unittest.TestCase):
    def setUp(self):
        import mem_mlp

        self.F = mem_mlp

    def test_hinge_recovers_mshr_limit(self):
        L = 110.0
        for m in (4, 8, 16, 32):
            ks = list(range(1, 49))
            ts = [L if k <= m else L * k / m for k in ks]
            c, _ = self.F.hinge(ks, ts)
            self.assertEqual(c, m)

    def test_gradual_curve_has_no_consistent_knee(self):
        ks = list(range(1, 49))
        ts = [150 * (1 + 0.02 * k) ** 1.5 for k in ks]  # rises from the start, never flat
        c, _ = self.F.hinge(ks, ts)
        plateau = ks[-1] * ts[0] / ts[-1]
        self.assertGreater(abs(plateau / c - 1), self.F.CONSIST)


class TestCacheCampaign(unittest.TestCase):
    def test_levels_and_fine_grid(self):
        import mem_cache as C

        xs = [4096 * 2 ** (k / 2) for k in range(12)]
        ys = [3, 3, 3, 3, 3, 3, 3.6, 17, 17, 17, 17, 160]
        lv = C.levels(xs, ys)
        self.assertEqual(len(lv), 1)  # the last point alone is no plateau
        lo, hi, a, b = lv[0]
        self.assertEqual((a, b), (3, 17))
        g = C.fine_grid(32768, 46336)
        steps = {b - a for a, b in zip(g, g[1:])}
        self.assertEqual(steps, {512})
        self.assertIn(32768, g)
        self.assertLessEqual(g[0], 32768 - 1024)
        self.assertGreaterEqual(g[-1], 46336)


@unittest.skipUnless(platform.machine() == "x86_64" and shutil.which("gcc"), "needs native x86-64 gcc")
class TestNative(unittest.TestCase):
    def test_l1_chase_is_fast(self):
        runs, sc = M.run_native(
            ["lat", "rand", 64, 4096, 2, 0, 1, 8192], cpu=os.environ.get("UARCHRE_TEST_CPU", 0)
        )
        v = runs["lat"][8192]
        self.assertEqual(len(v), 2)
        # an 8 KiB chase is an L1 hit: a few cycles, far below 50 TSC ticks
        self.assertLess(min(v), 50)
        self.assertGreater(sc["clock_ratio"], 0.2)


