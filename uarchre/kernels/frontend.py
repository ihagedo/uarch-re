"""Frontend kernels: P3.1 widths, P3.2 L1i, P3.3 BTB, P3.7 mispredict penalty.

Each kernel is one asm function `kern(laps, data)` in a small C harness that times `reps` calls, one line
per rep, so the cold rep 0 can be dropped. Spellings: RV (.option norvc, rdcycle/rdinstret) and A64 (a
counter from isa/aarch64.py; instructions retired only under gem5's PMU). Two gem5 rules: never close a
large lap with a conditional branch (RISC-V relaxes one past +-4 KiB into an inverted branch + j; A64
cbz/b.cond stop at +-1 MiB), and keep the probed stage the bottleneck (else fetch runs ahead and the
window hides isolated misses). Used by validation/gem5/fe_*.py.
"""

from dataclasses import dataclass, field
import random
import re

# RV64 spelling; norvc keeps every instruction 4 bytes so layouts are exact
RV = {
    "isa": "riscv64",
    "nop": "nop",
    "dec": "addi a0, a0, -1",
    "loop": "bnez a0, {label}",
    "exit_if_zero": "beqz a0, {label}",
    "jump": "j {label}",
    "slot": "fej{}",
    "fadd": "fadd.d {}, ft10, ft11",
    "fregs": [f"ft{k}" for k in range(8)],
    "insn_bytes": 4,
    # random_branches: a2 data pointer, a3 words left, t4 / t5 this / next word, t0 the bit
    "rb_lap": ["mv a2, a1", "li a3, {words}", "ld t5, 0(a2)"],
    "rb_word": ["mv t4, t5", "ld t5, 8(a2)", "addi a2, a2, 8"],  # a word ahead: no load on the resolve path
    "rb_branch": ["andi t0, t4, 1", "srli t4, t4, 1", "beqz t0, 1f", "addi t1, t1, 1", "1:"],
    "rb_next": ["addi a3, a3, -1", "bnez a3, 6b"],
}

# AArch64: x0 laps, x1 data; the harness claims x2-x7, d16-d23, d30-d31 and NZCV first (M1 rule)
A64 = {
    "isa": "aarch64",
    "nop": "nop",
    "dec": "sub x0, x0, #1",
    "loop": "cbnz x0, {label}",
    "exit_if_zero": "cbz x0, {label}",
    "jump": "b {label}",
    "slot": "Lfej{}",  # L: assembler-local on Mach-O, so the chain is not split into linker atoms
    "fadd": "fadd {}, d30, d31",
    "fregs": [f"d{k}" for k in range(16, 24)],
    "insn_bytes": 4,
    "rb_lap": ["mov x2, x1", "mov x3, #{words}", "ldr x5, [x2]"],
    "rb_word": ["mov x4, x5", "ldr x5, [x2, #8]", "add x2, x2, #8"],
    "rb_branch": ["and x6, x4, #1", "lsr x4, x4, #1", "cbz x6, 1f", "add x7, x7, #1", "1:"],
    "rb_next": ["sub x3, x3, #1", "cbnz x3, 6b"],
}
SPELLING = {"riscv64": RV, "aarch64": A64}


def _fadd(isa, k):
    return isa["fadd"].format(isa["fregs"][k])


@dataclass
class FEKernel:
    name: str
    asm: str  # body of kern(laps, data): a0, a1 (clobbers t0-t6, a0-a7) or x0, x1 (x0-x7, d16-d31)
    units_per_lap: float  # what one lap counts (iterations, branches, bytes)
    unit: str
    params: dict = field(default_factory=dict)
    data_words: int = 0  # 64-bit words of data the harness fills (a1)
    rep_stride: int = 0  # if > 0, rep r gets a1 = data + r * rep_stride words (fresh data per rep)
    isa: str = "riscv64"


HARNESS = r"""
/* generated by uarch-re (frontend): {name} */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

static inline uint64_t cyc(void) {{ uint64_t c; __asm__ __volatile__("rdcycle %0" : "=r"(c)); return c; }}
static inline uint64_t ins(void) {{ uint64_t c; __asm__ __volatile__("rdinstret %0" : "=r"(c)); return c; }}

void kern(uint64_t laps, uint64_t *data);
__asm__(
".text\n"
".p2align 12\n"
".globl kern\n"
".type kern, @function\n"
"kern:\n"
".option push\n"
".option norvc\n"
{asm}
".option pop\n"
"ret\n"
".size kern, .-kern\n"
);

int main(int argc, char **argv) {{
    uint64_t laps = argc > 1 ? strtoull(argv[1], 0, 0) : 1;
    int reps      = argc > 2 ? atoi(argv[2]) : 3;
    uint64_t seed = argc > 3 ? strtoull(argv[3], 0, 0) : 0;
    int mode      = argc > 4 ? atoi(argv[4]) : 0;   /* data: 0 zero, 1 random, 2 fixed pattern */
    size_t words  = {data_words};
    uint64_t *data = 0;
    if (words) {{
        if (posix_memalign((void **)&data, 4096, words * 8)) return 1;
        uint64_t s = seed * 0x9E3779B97F4A7C15ull + 0x1234567ull;
        for (size_t i = 0; i < words; i++) {{
            s ^= s << 13; s ^= s >> 7; s ^= s << 17;
            data[i] = mode == 1 ? s : mode == 2 ? 0xAAAAAAAAAAAAAAAAull : 0;
        }}
    }}
    if (reps > 64) reps = 64;
    uint64_t c[64], n[64];
    for (int r = 0; r < reps; r++) {{
        uint64_t c0 = cyc(), i0 = ins();
        {kern_call}
        c[r] = cyc() - c0; n[r] = ins() - i0;
    }}
    for (int r = 0; r < reps; r++)
        printf("rep %d cycles %lu instret %lu\n", r, (unsigned long)c[r], (unsigned long)n[r]);
    return 0;
}}
"""


A64_HARNESS = r"""
/* generated by uarch-re (frontend, aarch64): {name} */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
{counter}{insts}
#ifdef __APPLE__
#define KERN "_kern"
#define KERN_TYPE ""
#define KERN_SIZE ""
#else
#define KERN "kern"
#define KERN_TYPE ".type kern, %function\n"
#define KERN_SIZE ".size kern, .-kern\n"
#endif

void kern(uint64_t laps, uint64_t *data);
__asm__(
".text\n"
".p2align 12\n"
".globl " KERN "\n"
KERN_TYPE
KERN ":\n"
{asm}
"ret\n"
KERN_SIZE
);

int main(int argc, char **argv) {{
    uint64_t laps = argc > 1 ? strtoull(argv[1], 0, 0) : 1;
    int reps      = argc > 2 ? atoi(argv[2]) : 3;
    uint64_t seed = argc > 3 ? strtoull(argv[3], 0, 0) : 0;
    int mode      = argc > 4 ? atoi(argv[4]) : 0;   /* data: 0 zero, 1 random, 2 fixed pattern */
    size_t words  = {data_words};
    uint64_t *data = 0;
    if (words) {{
        if (posix_memalign((void **)&data, 4096, words * 8)) return 1;
        uint64_t s = seed * 0x9E3779B97F4A7C15ull + 0x1234567ull;
        for (size_t i = 0; i < words; i++) {{
            s ^= s << 13; s ^= s >> 7; s ^= s << 17;
            data[i] = mode == 1 ? s : mode == 2 ? 0xAAAAAAAAAAAAAAAAull : 0;
        }}
    }}
    if (reps > 64) reps = 64;
    uint64_t c[64], n[64];
    for (int r = 0; r < reps; r++) {{
        uint64_t c0 = cycles(), i0 = insts();
        {kern_call}
        c[r] = cycles() - c0; n[r] = (uint32_t)(insts() - i0);
    }}
    for (int r = 0; r < reps; r++)
        printf("rep %d cycles %llu{ins_fmt}\n", r, (unsigned long long)c[r]{ins_arg});
    return 0;
}}
"""

# INST_RETIRED (0x08) on event counter 0: gem5's ArmPMU counts it (NOPs excluded), 32 bits wide
INSTS_PMU = r"""
__attribute__((constructor)) static void uarchre_insts_on(void) {
    __asm__ __volatile__("msr pmevtyper0_el0, %0\n\tmsr pmcntenset_el0, %1\n\tisb"
                         :: "r"((uint64_t)0x08), "r"((uint64_t)1) : "memory");
}
static inline uint64_t insts(void) {
    uint64_t c; __asm__ __volatile__("isb\n\tmrs %0, pmevcntr0_el0" : "=r"(c) :: "memory"); return c;
}
"""
INSTS_NONE = "\nstatic inline uint64_t insts(void) { return 0; }\n"


def _a64_claim():
    """Write every register the A64 kernels touch, and NZCV, before the first lap."""
    from ..backends.isa.aarch64 import SRC_A, SRC_B, _mov64

    out = _mov64("x6", SRC_A) + _mov64("x7", SRC_B) + ["mov x2, x6", "mov x3, x7", "mov x4, x6", "mov x5, x7"]
    out += ["scvtf d30, x6", "scvtf d31, x7"] + [f"fmov {d}, d30" for d in A64["fregs"]]
    return out + ["cmp x6, x7"]


def harness_c(k: FEKernel, counter: str = "pmccntr") -> str:
    """C source for k; `counter` (an isa/aarch64.py COUNTERS key) applies to AArch64 only."""
    asm = k.asm.strip().splitlines()
    if k.isa == "aarch64":
        asm = _a64_claim() + asm
    lines = "\n".join('"' + line.replace('"', '\\"') + '\\n"' for line in asm)
    call = "kern(laps, data);"
    if k.rep_stride:  # only these kernels get the offset, so other harnesses stay byte-identical
        call = f"kern(laps, data + (size_t)r * {k.rep_stride}u);"
    if k.isa == "riscv64":
        return HARNESS.format(name=k.name, asm=lines, data_words=k.data_words, kern_call=call)
    from ..backends.isa.aarch64 import COUNTERS

    pmu = counter == "pmccntr"  # gem5 only: the Linux and macOS counters have no instruction count
    return A64_HARNESS.format(
        name=k.name,
        counter=COUNTERS[counter],
        insts=INSTS_PMU if pmu else INSTS_NONE,
        asm=lines,
        data_words=k.data_words,
        kern_call=call,
        ins_fmt=" instret %llu" if pmu else "",
        ins_arg=", (unsigned long long)n[r]" if pmu else "",
    )


def parse_reps(out: str):
    """[(cycles, instret or None), ...] per rep."""
    reps = re.findall(r"^rep \d+ cycles (\d+)(?: instret (\d+))?", out, re.M)
    return [(int(c), int(i) if i else None) for c, i in reps]


# ---------------------------------------------------------------- P3.1 widths


def width_loop(L: int, align: int = 64, filler: str = "nop", isa=RV) -> FEKernel:
    """L instructions in one aligned fetch block, the last a taken loop branch.

    Fetch-limited: ceil(L / fetchWidth) cycles (a staircase); decode-limited: L / decodeWidth (a ramp).
    "nop" is an int ALU op on RISC-V (6 ALUs on gem5); "mix" adds fadds so issue never binds first."""
    if L < 2:
        raise ValueError("L >= 2 (addi + bnez)")
    if L * isa["insn_bytes"] > align:
        raise ValueError(f"L={L} does not fit in one {align}-byte block")
    body = [f".p2align {align.bit_length() - 1}", "1:"]
    if filler == "nop":
        body += [isa["nop"]] * (L - 2)
    elif filler == "mix":
        body += [isa["nop"] if i % 2 == 0 else _fadd(isa, (i // 2) % 8) for i in range(L - 2)]
    else:
        raise ValueError(filler)
    body += [isa["dec"], isa["loop"].format(label="1b")]
    tag = "" if filler == "nop" else f"_{filler}"
    params = {"L": L, "filler": filler}
    return FEKernel(f"fe_width{tag}_L{L}", "\n".join(body), 1, "iteration", params, isa=isa["isa"])


# ---------------------------------------------------------------- P3.2 L1i


def straight_nops(footprint: int, filler: str = "mix", isa=RV) -> FEKernel:
    """A loop over exactly `footprint` bytes of code per lap, closed by an unconditional jump.

    "mix" (nop, nop, fadd) is fetch-bound on gem5; with "nop" only, execution caps at 6 int ALUs,
    fetch runs ahead and the capacity reads one line high."""
    n = footprint // isa["insn_bytes"] - 3
    if filler == "nop":
        fill = [f".rept {n}", isa["nop"], ".endr"]
    elif filler == "mix":
        fill = [
            f".rept {n // 6}",
            isa["nop"],
            isa["nop"],
            _fadd(isa, 0),
            isa["nop"],
            isa["nop"],
            _fadd(isa, 1),
            ".endr",
        ] + [isa["nop"]] * (n % 6)
    else:
        raise ValueError(filler)
    body = [
        isa["jump"].format(label="1f"),
        "9:",
        isa["jump"].format(label="8f"),
        ".p2align 6",
        "1:",
        isa["exit_if_zero"].format(label="9b"),  # short backward branch: never relaxed
        isa["dec"],
        *fill,
        isa["jump"].format(label="1b"),
        "8:",
    ]
    tag = "l1i2" if filler == "nop" else "l1i3"
    return FEKernel(
        f"fe_{tag}_{footprint}",
        "\n".join(body),
        footprint,
        "byte",
        {"footprint": footprint, "insts": n + 3, "filler": filler},
        isa=isa["isa"],
    )


# ---------------------------------------------------------------- P3.3 BTB


def chain_order(n: int, seed: int):
    """Random cyclic order of slots 0..n-1 from slot 0, no slot followed by its
    sequential neighbour (every jump goes to a non-fall-through target)."""
    if n < 3:
        raise ValueError("n >= 3 (with 2 slots the only cycle falls through)")
    rng = random.Random(seed)
    rest = list(range(1, n))
    for _ in range(1000):
        rng.shuffle(rest)
        order = [0] + rest
        if all(order[i + 1] != order[i] + 1 for i in range(n - 1)):
            return order
    raise RuntimeError("could not draw an order")


def jump_chain(n: int, seed: int = 0, isa=RV) -> FEKernel:
    """n taken jumps in consecutive 4-byte slots (n consecutive BTB indices), visited in a random cycle.

    One lap = n taken jumps + a not-taken beqz + addi; the last jump in visiting order targets the beqz.
    """
    order = chain_order(n, seed)
    nxt = {order[i]: order[i + 1] for i in range(n - 1)}
    nxt[order[-1]] = None
    # the exit test branches backward: a forward one is relaxed (RISC-V) once the chain spans 4 KiB
    j = isa["jump"]
    body = [j.format(label="5f"), "9:", j.format(label="8f"), ".p2align 6", "5:"]
    body += [isa["exit_if_zero"].format(label="9b"), isa["dec"]]
    for s in range(n):
        tgt = "5b" if nxt[s] is None else isa["slot"].format(nxt[s])
        body += [isa["slot"].format(s) + ":", j.format(label=tgt)]
    body += ["8:"]
    params = {"n": n, "seed": seed}
    return FEKernel(f"fe_btb2_n{n}_s{seed}", "\n".join(body), n, "taken branch", params, isa=isa["isa"])


# ---------------------------------------------------------------- P3.7 mispredict


def random_branches(words: int = 512, isa=RV) -> FEKernel:
    """64 static conditional branches per data word, `words` words per lap (code and data in L1).

    Random words give each branch an independent bit (50 % mispredicts), each rep its own region since
    gem5's TournamentBP memorizes shared data; 0xAAAA... has the same taken fraction but is learnable.
    """
    body = [".p2align 6", "5:", *(ln.format(words=words) for ln in isa["rb_lap"]), ".p2align 6", "6:"]
    body += isa["rb_word"] + isa["rb_branch"] * 64 + isa["rb_next"]
    body += [isa["dec"], isa["loop"].format(label="5b")]
    return FEKernel(
        f"fe_mispredict_w{words}",
        "\n".join(body),
        64 * words,
        "branch",
        {"words": words},
        data_words=4 * words + 1,
        rep_stride=words,
        isa=isa["isa"],
    )


# ================================================================ analysis


def width_estimate(Ls, cpi):
    """Width from a width_loop sweep: dict(width, peak_ipc, shape, sse_stair, sse_ramp).

    width = round(max L / cycles); shape is the better fit, `staircase` (ceil(L / w): fetch, which
    stops at a taken branch) or `ramp` (L / w: a stage fed from a queue)."""
    import math

    ipc = [L / c for L, c in zip(Ls, cpi)]
    peak = max(ipc)
    w = int(round(peak))
    stair = sum((c - math.ceil(L / w)) ** 2 for L, c in zip(Ls, cpi))
    ramp = sum((c - max(1.0, L / w)) ** 2 for L, c in zip(Ls, cpi))
    return {
        "width": w,
        "peak_ipc": peak,
        "shape": "staircase" if stair < ramp else "ramp",
        "sse_stair": stair,
        "sse_ramp": ramp,
    }


def lap_excess(ns, cpu, base_ns):
    """Excess cycles per lap over a line a + b N fitted to T(N) = N * cpu(N) on
    `base_ns` (the plateau). ~0 below a capacity; past it each overflowing set
    adds (ways + 1) misses per lap."""
    import numpy as np

    ns = np.asarray(ns, float)
    T = ns * np.asarray(cpu, float)
    sel = np.isin(ns, np.asarray(base_ns, float))
    b, a = np.polyfit(ns[sel], T[sel], 1)
    return T - (a + b * ns)


def onset(ns, excess, tau):
    """Bracket [last N with excess <= tau, first N above it) of the first
    transition, scanning upward; None if no point exceeds tau."""
    pts = sorted(zip(ns, excess))
    for i, (n, e) in enumerate(pts):
        if e > tau:
            return (pts[i - 1][0] if i else None, n)
    return None
