_COMMON = r"""
/* generated by uarchre/kernels/memory.py (P2 memory probes) */
#define _GNU_SOURCE
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#ifdef __x86_64__
#include <sys/mman.h>
#endif

@CYCLES@

#define UNROLL @UNROLL@
@WARM_CAP@

static uint64_t rs = 88172645463325252ULL;
static inline uint64_t xs(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }

static void *chase(void *p, uint64_t n) {
    n /= UNROLL;
    if (!n) return p;
    __asm__ __volatile__(
@CHASE@
        : "+r"(p), "+r"(n) :: "memory", "cc");
    return p;
}

/* independent strided loads: n loads, address = base + i*stride (wraps in C
   every block of UNROLL loads), loaded values summed into acc. The position
   persists across calls (indep_off), so timed reps continue the stream
   instead of re-reading lines the previous call just cached. */
static size_t indep_off = 0;
static uint64_t indep(char *base, size_t bytes, size_t stride, uint64_t n) {
    uint64_t acc = 0;
    size_t off = indep_off, blk = (size_t)UNROLL * stride;
    for (uint64_t i = 0; i < n / UNROLL; i++) {
        char *p = base + off;
        __asm__ __volatile__(
@INDEP@
            : "+r"(acc) : "r"(p), "r"(stride) : "memory", "cc"@INDEP_CLOB@);
        off += blk;
        if (off + blk > bytes) off = 0;
    }
    indep_off = off;
    return acc;
}

static char *alloc(size_t bytes, int pages) {
    char *buf = NULL;
    size_t align = 4096;
#ifdef __x86_64__
    if (pages == 2) { align = 2u << 20; bytes = (bytes + align - 1) & ~(align - 1); }
#endif
    if (posix_memalign((void **)&buf, align, bytes)) { perror("alloc"); exit(1); }
#ifdef __x86_64__
    if (pages == 1) madvise(buf, bytes, MADV_NOHUGEPAGE);
    if (pages == 2) madvise(buf, bytes, MADV_HUGEPAGE);
#else
    (void)pages;
#endif
#ifdef __x86_64__
    memset(buf, 0, bytes);
#else
    /* gem5 SE maps zeroed pages on first touch, frames in touch order: touch
       pages in address order so the buffer is physically contiguous */
    for (size_t o = 0; o < bytes; o += 4096) buf[o] = 0;
#endif
    return buf;
}

/* perm = random cyclic permutation of 0..n-1 (Sattolo); caller frees */
static size_t *cyclic(size_t n, uint64_t seed) {
    size_t *perm = malloc(n * sizeof(size_t));
    for (size_t i = 0; i < n; i++) perm[i] = i;
    rs = seed | 1;
    for (size_t i = n - 1; i > 0; i--) {
        size_t j = xs() % i;
        size_t t = perm[i]; perm[i] = perm[j]; perm[j] = t;
    }
    return perm;
}

/* link node addr(perm[i]) -> addr(perm[i+1]) for node addresses buf + off[k] */
static void link_nodes(char *buf, const size_t *off, const size_t *perm, size_t n) {
    for (size_t i = 0; i < n; i++)
        *(void **)(buf + off[perm[i]]) = buf + off[perm[(i + 1) % n]];
}

static void *build(char *buf, size_t nodes, size_t stride, int rnd, uint64_t seed) {
    if (!rnd) {
        for (size_t i = 0; i < nodes; i++)
            *(void **)(buf + i * stride) = buf + ((i + 1) % nodes) * stride;
        return buf;
    }
    size_t *perm = cyclic(nodes, seed);
    for (size_t i = 0; i + 1 < nodes; i++)
        *(void **)(buf + perm[i] * stride) = buf + perm[i + 1] * stride;
    *(void **)(buf + perm[nodes - 1] * stride) = buf + perm[0] * stride;
    void *start = buf + perm[0] * stride;
    free(perm);
    return start;
}

static uint64_t warm_cap = WARM_CAP;    /* a "w=<loads>" argument overrides */
static int warm_token(const char *s) {
    if (s[0] != 'w' || s[1] != '=') return 0;
    warm_cap = strtoull(s + 2, 0, 0);
    return 1;
}
static void *warm(void *p, size_t nodes) {
    uint64_t w = 2ULL * nodes;
    if (w > warm_cap) w = warm_cap;
    return chase(p, (w + UNROLL - 1) / UNROLL * UNROLL);
}

static uint64_t parse(const char *s) { return strtoull(s, 0, 0); }

static void timed(const char *tag, uint64_t key, void **pp, uint64_t n, int reps, double per) {
    void *p = *pp;
    n = (n + UNROLL - 1) / UNROLL * UNROLL;
    double *v = malloc(reps * sizeof(double));
    for (int r = 0; r < reps; r++) {
        uint64_t t0 = cycles();
        p = chase(p, n);
        uint64_t t1 = cycles();
        v[r] = (double)(t1 - t0) / ((double)n / per);
    }
    __asm__ __volatile__("" :: "r"(p));
    for (int r = 0; r < reps; r++) printf("R %s %llu %d %.4f\n", tag, (unsigned long long)key, r, v[r]);
    fflush(stdout);
    free(v);
    *pp = p;
}

#ifdef __x86_64__
static double tsc_hz(void) {
    struct timespec a, b;
    clock_gettime(CLOCK_MONOTONIC, &a);
    uint64_t t0 = cycles();
    do clock_gettime(CLOCK_MONOTONIC, &b);
    while ((b.tv_sec - a.tv_sec) * 1e9 + (b.tv_nsec - a.tv_nsec) < 2e7);
    uint64_t t1 = cycles();
    return (t1 - t0) / ((b.tv_sec - a.tv_sec) + (b.tv_nsec - a.tv_nsec) * 1e-9);
}
/* TSC ticks per dependent reg-reg add (= per core cycle) */
static double clock_ratio(void) {
    uint64_t x = 0, n = 1 << 14;
    uint64_t t0 = cycles();
    __asm__ __volatile__(
        "1:\n\t"
@PROBE@
        "decq %1\n\tjnz 1b\n\t" : "+r"(x), "+r"(n) :: "cc");
    uint64_t t1 = cycles();
    __asm__ __volatile__("" :: "r"(x));
    return (double)(t1 - t0) / (double)((1 << 14) * 64);
}
#endif

#define LINE @LINE@
@TEMPLATE_CHAIN@
#undef LINE

@MLP@

/* usage: memprobe <mode> ...; every timed rep prints "R <tag> <key> <rep> <cycles>"
     lat <rand|seq> <stride> <nloads> <reps> <pages> <seed> F...  chase over F bytes, a node per stride
     indep <stride> <nloads> <reps> <pages> F...                   independent strided loads
     pair <slot> <nloads> <reps> <F> D...                          X -> X+D -> next slot (per pair)
     conflict <S> <nloads> <reps> <pages> K...                     K random nodes S bytes apart
     page <nloads> <reps> <pages> <dense> P...                     a node per @PAGE@ page; dense=1 packs
     wchain <F> <nloads> <reps> <m5>                               the window probe's chains: A, A+B
@MLP_USAGE@
   "w=<loads>" caps warm-up for the footprints after it (default 2 passes). <pages> (x86): 0 = 4 KiB
   aligned like the window template, 1 = MADV_NOHUGEPAGE, 2 = 2 MiB aligned + MADV_HUGEPAGE. */
int main(int argc, char **argv) {
    if (argc < 2) { fprintf(stderr, "usage: see uarchre/kernels/memory.py\n"); return 2; }
    const char *mode = argv[1];
#ifdef __x86_64__
    printf("tsc_hz %.0f\n", tsc_hz());
    printf("clock_ratio %.4f\n", clock_ratio());
#endif
    if (!strcmp(mode, "lat") || !strcmp(mode, "indep")) {
        int is_lat = !strcmp(mode, "lat");
        int a = 2;
        int rnd = 1;
        if (is_lat) rnd = !strcmp(argv[a++], "rand");
        size_t stride = parse(argv[a++]);
        uint64_t nloads = parse(argv[a++]);
        int reps = atoi(argv[a++]);
        int pages = atoi(argv[a++]);
        uint64_t seed = is_lat ? parse(argv[a++]) : 1;
        /* one buffer for every footprint, allocated and touched in order once:
           under gem5 SE that makes it physically contiguous (per-footprint
           allocations reuse heap pages touched earlier in another order, and
           the uneven set mapping then shifts the capacity knee) */
        size_t fmax = 0;
        for (int b = a; b < argc; b++) if (argv[b][0] != 'w' && parse(argv[b]) > fmax) fmax = parse(argv[b]);
        char *buf = alloc(fmax + 64, pages);
        for (; a < argc; a++) {
            if (warm_token(argv[a])) continue;
            size_t F = parse(argv[a]);
            size_t nodes = F / stride;
            if (nodes < 2) continue;
            indep_off = 0;
            if (is_lat) {
                void *p = build(buf, nodes, stride, rnd, seed + F);
                p = warm(p, nodes);
                timed("lat", F, &p, nloads, reps, 1.0);
            } else {
                uint64_t n = (nloads + UNROLL - 1) / UNROLL * UNROLL;
                volatile uint64_t sink = indep(buf, nodes * stride, stride, n < 2 * nodes ? n : 2 * nodes);
                double *v = malloc(reps * sizeof(double));
                for (int r = 0; r < reps; r++) {
                    uint64_t t0 = cycles();
                    sink += indep(buf, nodes * stride, stride, n);
                    uint64_t t1 = cycles();
                    v[r] = (double)(t1 - t0) / (double)n;
                }
                for (int r = 0; r < reps; r++) printf("R indep %zu %d %.4f\n", F, r, v[r]);
                fflush(stdout);
                free(v);
                (void)sink;
            }
        }
        free(buf);
    } else if (!strcmp(mode, "pair")) {
        size_t slot = parse(argv[2]);
        uint64_t nloads = parse(argv[3]);
        int reps = atoi(argv[4]);
        size_t F = parse(argv[5]);
        size_t slots = F / slot;
        char *buf = alloc(F + 64, 0);
        for (int a = 6; a < argc; a++) {
            size_t d = parse(argv[a]);
            size_t *perm = cyclic(slots, 0xabcd + d);
            for (size_t i = 0; i < slots; i++) {
                char *x = buf + perm[i] * slot;
                char *y = buf + perm[(i + 1) % slots] * slot;
                *(void **)x = x + d;
                *(void **)(x + d) = y;
            }
            void *p = buf + perm[0] * slot;
            free(perm);
            p = warm(p, 2 * slots);
            timed("pair", d, &p, nloads, reps, 2.0);
        }
        free(buf);
    } else if (!strcmp(mode, "conflict")) {
        size_t S = parse(argv[2]);
        uint64_t nloads = parse(argv[3]);
        int reps = atoi(argv[4]);
        int pages = atoi(argv[5]);
        size_t kmax = 0;
        for (int a = 6; a < argc; a++) if (argv[a][0] != 'w' && parse(argv[a]) > kmax) kmax = parse(argv[a]);
        char *buf = alloc(kmax * S + 64, pages);
        for (int a = 6; a < argc; a++) {
            if (warm_token(argv[a])) continue;
            size_t K = parse(argv[a]);
            void *p = build(buf, K, S, 1, 0x77 + K);
            p = warm(p, K < 64 ? 64 : K);
            timed("conflict", K, &p, nloads, reps, 1.0);
        }
        free(buf);
    } else if (!strcmp(mode, "page")) {
        uint64_t nloads = parse(argv[2]);
        int reps = atoi(argv[3]);
        int pages = atoi(argv[4]);
        int dense = atoi(argv[5]);
        for (int a = 6; a < argc; a++) {
            if (warm_token(argv[a])) continue;
            size_t P = parse(argv[a]);
            size_t bytes = dense ? P * @LN@ : P * @PG@;
            char *buf = alloc(bytes + @PG@, pages);
            size_t *off = malloc(P * sizeof(size_t));
            /* line in page i: (i + i/64) mod 64 -- every prefix spreads over the
               64 L1 sets, and with the page's low 3 bits it reaches all 512 sets
               of a 32 KiB-span L2 (plain i mod 64 would hit only 64 of them) */
            for (size_t i = 0; i < P; i++) off[i] = dense ? i * @LN@ : i * @PG@ + ((i + i / @LPP@) % @LPP@) * @LN@;
            size_t *perm = cyclic(P, 0x99 + P);
            link_nodes(buf, off, perm, P);
            void *p = buf + off[perm[0]];
            free(off); free(perm);
            p = warm(p, P < 4096 ? 4096 : P);
            timed(dense ? "dense" : "page", P, &p, nloads, reps, 1.0);
            free(buf);
        }
    } else if (!strcmp(mode, "wchain")) {
        size_t bytes = parse(argv[2]);
        uint64_t nloads = parse(argv[3]);
        int reps = atoi(argv[4]);
        int m5 = argc > 5 ? atoi(argv[5]) : 0;
        size_t nodes = bytes / 64;
        /* exactly the template's build_chain: buffer, then perm by seed */
        (void)nodes;
        /* the window template's own build_chain (copied from isa_base.C_TEMPLATE
           at generation time), same seeds as its seed 0 */
        void *a0 = build_chain(bytes, 0x1234);
        void *a1 = build_chain(bytes, 0x5678);
        void *p = a0;
        if (m5) M5_RESET();
        timed("wchainA", bytes, &p, nloads, reps, 1.0);
        if (m5) M5_DUMP();
        /* A and B interleaved: two independent misses per pair */
        void *q = a1;
        double *v = malloc(reps * sizeof(double));
        uint64_t n = (nloads + UNROLL - 1) / UNROLL * UNROLL;
        for (int r = 0; r < reps; r++) {
            uint64_t t0 = cycles();
            for (uint64_t i = 0; i < n / UNROLL; i++) { p = chase2(p, &q); }
            uint64_t t1 = cycles();
            v[r] = (double)(t1 - t0) / ((double)n / 2.0);
        }
        __asm__ __volatile__("" :: "r"(p), "r"(q));
        for (int r = 0; r < reps; r++) printf("R wchainAB %zu %d %.4f\n", bytes, r, v[r]);
        if (m5) M5_DUMP();
    } else if (!strcmp(mode, "mlp")) {
        return mlp_main(argc, argv);
@MODES@    } else {
        fprintf(stderr, "unknown mode %s\n", mode);
        return 2;
    }
    return 0;
}
"""  # noqa: E501


def _asm(lines):
    return "\n".join(f'        "{line}\\n\\t"' for line in lines)


_RISCV_CYCLES = r"""
static inline uint64_t cycles(void) {
    uint64_t c; __asm__ __volatile__("rdcycle %0" : "=r"(c) :: "memory"); return c;
}
/* gem5 pseudo-ops (custom-3 opcode, func in bits 31:25): 0x40 reset_stats,
   0x41 dump_stats; a0 = delay, a1 = period */
#define M5_RESET() __asm__ __volatile__("li a0, 0\n\tli a1, 0\n\t.long 0x8000007b" ::: "a0", "a1", "memory")
#define M5_DUMP()  __asm__ __volatile__("li a0, 0\n\tli a1, 0\n\t.long 0x8200007b" ::: "a0", "a1", "memory")
/* one link each of chains p and *q, UNROLL/2 times each, interleaved */
static void *chase2(void *p, void **q) {
    void *b = *q;
    __asm__ __volatile__(
@CHASE2@
        : "+r"(p), "+r"(b) :: "memory");
    *q = b;
    return p;
}
"""

