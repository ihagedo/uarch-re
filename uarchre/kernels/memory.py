def chase_source(isa="riscv64", counter="pmccntr") -> str:
    """`counter` (aarch64 only): a key of aarch64.COUNTERS."""
    sub = dict(_X86_RISCV)
    if isa == "riscv64":
        chase = ["1:"] + ["ld %0, 0(%0)"] * UNROLL + ["addi %1, %1, -1", "bnez %1, 1b"]
        chase2 = ["ld %0, 0(%0)", "ld %1, 0(%1)"] * (UNROLL // 2)
        indep = ["mv t1, %1"]  # t1 = running address p + i*stride
        for _ in range(UNROLL):
            indep += ["ld t0, 0(t1)", "add %0, %0, t0", "add t1, t1, %2"]
        cyc = _RISCV_CYCLES.replace("@CHASE2@", _asm(chase2))
        mlp = _mlp_riscv()
        indep_clob = ', "t0", "t1"'
        probe = ""
    elif isa == "x86_64":
        chase = ["1:"] + ["movq (%0), %0"] * UNROLL + ["decq %1", "jnz 1b"]
        chase2 = ["movq (%0), %0", "movq (%1), %1"] * (UNROLL // 2)
        indep = ["movq %1, %%r8"]
        for _ in range(UNROLL):
            indep += ["addq (%%r8), %0", "addq %2, %%r8"]
        cyc = _X86_CYCLES.replace("@CHASE2@", _asm(chase2))
        mlp = (
            "static int mlp_main(int argc, char **argv) { (void)argc; (void)argv; "
            'fprintf(stderr, "mlp: riscv64 only\\n"); return 2; }'
        )
        indep_clob = ', "r8"'
        probe = _asm(["addq %1, %0"] * 64)
    elif isa == "aarch64":
        chase = ["cmp %0, %1", "1:"] + ["ldr %0, [%0]"] * UNROLL + ["subs %1, %1, #1", "b.ne 1b"]
        chase2 = ["ldr %0, [%0]", "ldr %1, [%1]"] * (UNROLL // 2)
        indep = ["mov x9, %1"]
        for _ in range(UNROLL):
            indep += ["ldr x10, [x9]", "add %0, %0, x10", "add x9, x9, %2"]
        cyc = _a64_cycles(counter, _asm(chase2))
        mlp = _mlp_aarch64() + _A64_CODE + _A64_MORE.replace("@BW@", _bw())
        indep_clob = ', "x9", "x10"'
        probe = ""
        sub = {**_A64, "@WARM_CAP@": _A64_WARM[counter == "pmccntr"]}
    else:
        raise ValueError(isa)
    src = _COMMON
    for k, v in {
        "@CYCLES@": cyc,
        "@UNROLL@": str(UNROLL),
        "@CHASE@": _asm(chase),
        "@INDEP@": _asm(indep),
        "@INDEP_CLOB@": indep_clob,
        "@PROBE@": probe,
        "@MLP@": mlp,
        "@TEMPLATE_CHAIN@": template_chain_c(),
        **sub,
    }.items():
        src = src.replace(k, v)
    return src


