def plateau_onset(xs, ys, lo_level, hi_level, frac=0.1):
    """Capacity bracket (last x below lo + frac*(hi-lo), first x at or above it) between two plateaus.

    With LRU the miss fraction ramps from 0 at capacity C to 1 at C(1 + 1/assoc), so C is where the
    rise starts, not the middle of the step."""
    thr = lo_level + frac * (hi_level - lo_level)
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    last_lo, first_hi = None, None
    for i in order:
        if ys[i] < thr:
            if first_hi is None:
                last_lo = xs[i]
        elif first_hi is None and last_lo is not None:
            first_hi = xs[i]
    return last_lo, first_hi


# ------------------------------------------------- bare-metal TLB probe (P2.2)
# gem5 SE never consults the RISC-V TLB, so this runs bare metal under FS (mem_fs_config.py), in S-mode.
# Code, stack and Sv39 tables share one identity-mapped gigapage (one TLB entry); probe pages at VA 4 GiB.

BM_NPMAX = 16384

_BM_SRC = r"""
/* generated by uarchre/kernels/memory.py: bare-metal Sv39 dTLB probe */
#include <stdint.h>
#define PAGE 4096UL
#define VA_BASE 0x100000000UL
#define PA_PT 0x88000000UL
#define PA_DATA 0x90000000UL
#define VA_CODE 0x200000000UL
#define PA_CODE 0x98000000UL
#define ITLB @ITLB@                 /* 1: probe the itb with code pages instead */
#define NPMAX @NPMAX@
#define NLOADS @NLOADS@ULL
#define REPS @REPS@
#define UNROLL 16
static const uint32_t PLIST[] = { @PLIST@ };
#define NPL (sizeof(PLIST) / sizeof(PLIST[0]))

void *memset(void *d, int c, unsigned long n) { unsigned char *p = d; while (n--) *p++ = (unsigned char)c; return d; }
void *memcpy(void *d, const void *s, unsigned long n) { unsigned char *a = d; const unsigned char *b = s; while (n--) *a++ = *b++; return d; }

__asm__(".section .text.init\n.globl _start\n_start:\n\tla sp, _stack_top\n\tcall mmain\n1:\tj 1b\n"
        ".align 4\n.globl trap_entry\ntrap_entry:\n\tcsrr a1, mcause\n\taddi a1, a1, 1\n\tli a0, 0\n"
        "\t.long 0x4400007b\n2:\tj 2b\n.text\n");

static inline void m5_reset(void) { __asm__ __volatile__("li a0, 0\n\tli a1, 0\n\t.long 0x8000007b" ::: "a0", "a1", "memory"); }
static inline void m5_dump(void)  { __asm__ __volatile__("li a0, 0\n\tli a1, 0\n\t.long 0x8200007b" ::: "a0", "a1", "memory"); }
static inline void m5_exit(void)  { __asm__ __volatile__("li a0, 0\n\t.long 0x4200007b" ::: "a0", "memory"); }

static uint32_t perm[NPMAX];
static uint64_t rs = 88172645463325252ULL;
static inline uint64_t xs(void) { rs ^= rs << 13; rs ^= rs >> 7; rs ^= rs << 17; return rs; }

static void *chase(void *p, uint64_t n) {
    n /= UNROLL;
    if (!n) return p;
    __asm__ __volatile__(
@CHASE@
        : "+r"(p), "+r"(n) :: "memory");
    return p;
}

static inline char *node(uint64_t i) { return (char *)(VA_BASE + i * PAGE + ((i + i / 64) % 64) * 64); }

static inline uint32_t *stub(uint64_t i) { return (uint32_t *)(VA_CODE + i * PAGE + ((i + i / 64) % 64) * 64); }

/* stub in code page `from`: count a0 down, return to ra at 0, else jump to
   the stub in page `to` (auipc + jalr reach any offset in +-2 GiB) */
static void write_stub(uint64_t from, uint64_t to) {
    uint32_t *s = stub(from);
    int64_t off = (int64_t)((uint64_t)stub(to) - (uint64_t)(s + 3));
    int64_t hi = (off + 0x800) >> 12, lo = off - (hi << 12);
    s[0] = 0xfff50513u;                                  /* addi a0, a0, -1 */
    s[1] = 0x00051463u;                                  /* bnez a0, +8     */
    s[2] = 0x00008067u;                                  /* ret             */
    s[3] = ((uint32_t)hi << 12) | (5u << 7) | 0x17u;     /* auipc t0, hi    */
    s[4] = ((uint32_t)lo << 20) | (5u << 15) | 0x67u;    /* jalr x0, lo(t0) */
}

static inline void run_stubs(void *entry, uint64_t n) {
    register uint64_t a0 __asm__("a0") = n;
    __asm__ __volatile__("jalr ra, 0(%1)" : "+r"(a0) : "r"(entry) : "ra", "t0", "memory");
}

static void smain(void) {
    for (unsigned k = 0; k < NPL; k++) {
        uint64_t P = PLIST[k];
        for (uint64_t i = 0; i < P; i++) perm[i] = (uint32_t)i;
        rs = 0x5151 + P;
        for (uint64_t i = P - 1; i > 0; i--) {
            uint64_t j = (uint64_t)(((unsigned __int128)xs() * i) >> 64);
            uint32_t t = perm[i]; perm[i] = perm[j]; perm[j] = t;
        }
#if ITLB
        for (uint64_t i = 0; i < P; i++) write_stub(perm[i], perm[(i + 1) % P]);
        __asm__ __volatile__("fence.i" ::: "memory");
        void *entry = stub(perm[0]);
        run_stubs(entry, (2 * P + 64));
        m5_reset();
        for (int r = 0; r < REPS; r++) run_stubs(entry, NLOADS);
        m5_dump();
        continue;
#endif
        for (uint64_t i = 0; i < P; i++) *(void **)node(perm[i]) = node(perm[(i + 1) % P]);
        void *p = node(perm[0]);
        uint64_t w = (2 * P + 64 + UNROLL - 1) / UNROLL * UNROLL;
        p = chase(p, w);
        m5_reset();
        for (int r = 0; r < REPS; r++) p = chase(p, NLOADS);
        m5_dump();
        __asm__ __volatile__("" :: "r"(p));
    }
    m5_exit();
    for (;;) ;
}

#define PTE(pa, fl) ((((uint64_t)(pa)) >> 12) << 10 | (fl))
enum { V = 1, R = 2, W = 4, X = 8, A = 64, D = 128 };

void mmain(void) {
    __asm__ __volatile__("la t0, trap_entry\n\tcsrw mtvec, t0" ::: "t0");
    __asm__ __volatile__("li t0, -1\n\tcsrw pmpaddr0, t0\n\tli t0, 0x1f\n\tcsrw pmpcfg0, t0" ::: "t0");
    __asm__ __volatile__("li t0, 7\n\tcsrw mcounteren, t0" ::: "t0");
    volatile uint64_t *root = (uint64_t *)PA_PT, *l1 = root + 512, *l0 = l1 + 512;
    for (uint64_t i = 0; i < 1024 + NPMAX; i++) root[i] = 0;
    root[2] = PTE(0x80000000UL, V | R | W | X | A | D);          /* code, data, stack, tables */
    root[4] = PTE((uint64_t)l1, V);                              /* VA 4 GiB: probe region */
    for (uint64_t t = 0; t < (NPMAX + 511) / 512; t++) l1[t] = PTE((uint64_t)(l0 + 512 * t), V);
    for (uint64_t p = 0; p < NPMAX; p++) l0[p] = PTE(PA_DATA + p * PAGE, V | R | W | A | D);
#if ITLB
    volatile uint64_t *l1c = l0 + NPMAX, *l0c = l1c + 512;     /* VA 8 GiB: code pages */
    for (uint64_t i = 0; i < 512 + NPMAX; i++) l1c[i] = 0;
    root[8] = PTE((uint64_t)l1c, V);
    for (uint64_t t = 0; t < (NPMAX + 511) / 512; t++) l1c[t] = PTE((uint64_t)(l0c + 512 * t), V);
    for (uint64_t p = 0; p < NPMAX; p++) l0c[p] = PTE(PA_CODE + p * PAGE, V | R | W | X | A | D);
#endif
    uint64_t satp = (8UL << 60) | (PA_PT >> 12);
    __asm__ __volatile__("csrw satp, %0\n\tsfence.vma" :: "r"(satp) : "memory");
    uint64_t ms;
    __asm__ __volatile__("csrr %0, mstatus" : "=r"(ms));
    ms = (ms & ~(3UL << 11)) | (1UL << 11) | (1UL << 13);       /* MPP = S, FS = initial */
    __asm__ __volatile__("csrw mstatus, %0\n\tcsrw mepc, %1\n\tmret" :: "r"(ms), "r"(smain) : "memory");
    for (;;) ;
}
"""  # noqa: E501

_BM_LD = """OUTPUT_ARCH(riscv)
ENTRY(_start)
SECTIONS {
  . = 0x80000000;
  .text : { *(.text.init) *(.text*) }
  .rodata : { *(.rodata*) *(.srodata*) }
  .data : { *(.data*) *(.sdata*) }
  .bss : { *(.bss*) *(.sbss*) *(COMMON) }
  . = ALIGN(4096);
  . += 0x10000;
  _stack_top = .;
}
"""


def tlb_baremetal_source(plist, nloads=1024, reps=3, itlb=False):
    """Per P: a random chain over P pages, two warm passes, then REPS x NLOADS loads between reset_stats
    and dump_stats (dump i is plist[i]; cycles per load = numCycles / (REPS * NLOADS)). itlb=True chases
    P code pages instead, each a 5-instruction stub jumping to the next; `nloads` is then jumps per rep."""
    chase = ["1:"] + ["ld %0, 0(%0)"] * UNROLL + ["addi %1, %1, -1", "bnez %1, 1b"]
    src = _BM_SRC
    for k, v in {
        "@NPMAX@": str(BM_NPMAX),
        "@NLOADS@": str(nloads),
        "@REPS@": str(reps),
        "@ITLB@": "1" if itlb else "0",
        "@PLIST@": ", ".join(str(int(p)) for p in plist),
        "@CHASE@": _asm(chase),
    }.items():
        src = src.replace(k, v)
    if max(plist) > BM_NPMAX:
        raise ValueError(f"P up to {BM_NPMAX}")
    return src


def tlb_baremetal_binary(plist, nloads=1024, reps=3, itlb=False):
    """Compile (cached by content hash) a bare-metal ELF for mem_fs_config.py."""
    import hashlib
    import os
    import subprocess

    src = tlb_baremetal_source(plist, nloads, reps, itlb)
    h = hashlib.md5((src + _BM_LD).encode()).hexdigest()[:10]
    d = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "build", "baremetal"))
    os.makedirs(d, exist_ok=True)
    elf = os.path.join(d, f"tlbprobe_{h}.elf")
    if not os.path.exists(elf):
        c, ld = os.path.join(d, f"tlbprobe_{h}.c"), os.path.join(d, "baremetal.ld")
        with open(c, "w") as fh:
            fh.write(src)
        with open(ld, "w") as fh:
            fh.write(_BM_LD)
        import threading

        tmp = f"{elf}.{os.getpid()}.{threading.get_ident()}"
        subprocess.run(
            [
                "riscv64-linux-gnu-gcc",
                "-O2",
                "-march=rv64gc",
                "-mabi=lp64d",
                "-mcmodel=medany",
                "-ffreestanding",
                "-fno-builtin",
                "-nostdlib",
                "-nostartfiles",
                "-static",
                "-no-pie",
                "-fno-pie",
                "-mno-relax",
                "-T",
                ld,
                "-Wl,--build-id=none",
                c,
                "-o",
                tmp,
            ],
            check=True,
        )
        os.replace(tmp, elf)
    return elf


def run_gem5_fs(elf, sets=(), tag="tlb"):
    """Run a bare-metal ELF under validation/gem5/mem_fs_config.py, holding
    one host-wide gem5 slot. Returns (stdout, outdir)."""
    import hashlib
    import os
    import subprocess
    from ..backends.platform.gem5 import slot, GEM5, CPUS, ROOT

    cfg = os.path.join(ROOT, "validation", "gem5", "mem_fs_config.py")
    tail = [cfg, "--bin", elf] + [x for s in sets for x in ("--set", s)]
    outdir = os.path.join(
        ROOT, "build", "gem5out", f"{tag}_{hashlib.md5(' '.join(tail).encode()).hexdigest()[:10]}"
    )
    os.makedirs(outdir, exist_ok=True)
    cmd = ["taskset", "-c", CPUS, GEM5["riscv64"], "-q", "--outdir", outdir, *tail]
    with slot():
        r = subprocess.run(cmd, capture_output=True, text=True)
    # the probe ends with m5_exit; its trap handler ends with m5_fail(mcause + 1)
    if r.returncode != 0 or "m5_exit instruction encountered" not in r.stdout:
        raise RuntimeError(f"gem5 FS failed ({r.returncode}):\n{r.stdout[-2000:]}\n{r.stderr[-3000:]}")
    return r.stdout, outdir


# ------------------------------------------------ memory dependence probe (P2.5)
# gem5 SE, riscv64 or aarch64. A load that runs ahead of its aliasing store squashes until the store-set
# predictor (SSIT, direct mapped on PC/4) pairs them; N 4-instruction blocks overflow it at SSITSize/4.

MEMDEP_NMAX = 384
_MD_BASES = ["s1", "s3", "s7"]  # slot bases buf, +2048, +4096 (imm12 reaches 128 slots each)
_MD_NOALIAS = ["s4", "s5", "s8"]  # the same + 8192: never the same slot


def _memdep_fn(n, alias=True):
    """Block j: divu t1 (s2 = 1, a late store address); sd a0, off_j(t1); ld a1 from slot j (alias) or
    8 KiB above it; nop. Slots are 16 B apart, gem5's order-check granularity (LSQDepCheckShift = 4)."""
    body = [".option push", ".option norvc", ".p2align 6", "1:"]
    for j in range(n):
        base, sl = _MD_BASES[j // 128], j % 128
        off = 16 * sl
        lbase = base if alias else _MD_NOALIAS[j // 128]
        body += [f"divu t1, {base}, s2", f"sd a0, {off}(t1)", f"ld a1, {off}({lbase})", "nop"]
    body += ["addi s6, s6, -1", "bnez s6, 1b", ".option pop"]
    lines = "\n".join(f'        "{line}\\n\\t"' for line in body)
    tag = "a" if alias else "n"
    return (
        f"static void md{tag}_{n}(char *buf, uint64_t iters) {{\n"
        f"    __asm__ __volatile__(\n"
        f'        "mv s1, %0\\n\\t" "addi s3, %0, 2047\\n\\t" "addi s3, s3, 1\\n\\t"\n'
        f'        "addi s7, s3, 2047\\n\\t" "addi s7, s7, 1\\n\\t"\n'
        f'        "li t0, 8192\\n\\t" "add s4, s1, t0\\n\\t" "add s5, s3, t0\\n\\t" "add s8, s7, t0\\n\\t"\n'
        f'        "li s2, 1\\n\\t" "li a0, 7\\n\\t" "mv s6, %1\\n\\t"\n'
        f"{lines}\n"
        f'        :: "r"(buf), "r"(iters) : "memory", "t0", "t1", "a0", "a1", '
        f'"s1", "s2", "s3", "s4", "s5", "s6", "s7", "s8");\n}}'
    )


def _memdep_fn_a64(n, alias=True):
    """_memdep_fn on AArch64: udiv x9 (x8 = 1); str x12, [x9, off_j]; ldr x14 from slot j or 8 KiB
    above it (x11); nop. One base reaches every slot (scaled imm12)."""
    from ..backends.isa.aarch64 import SRC_A, _mov64

    body = ["mov x10, %0", "add x11, x10, #8192", "mov x8, #1", *_mov64("x12", SRC_A), "mov x13, %1"]
    body += ["mov x9, x10", "mov x14, x12", "cmp x13, x8", ".p2align 6", "1:"]  # claim x9, x14, NZCV
    for j in range(n):
        lbase = "x10" if alias else "x11"
        body += ["udiv x9, x10, x8", f"str x12, [x9, #{16 * j}]", f"ldr x14, [{lbase}, #{16 * j}]", "nop"]
    body += ["subs x13, x13, #1", "b.ne 1b"]
    tag = "a" if alias else "n"
    clob = ", ".join(f'"x{i}"' for i in range(8, 15))
    return (
        f"static void md{tag}_{n}(char *buf, uint64_t iters) {{\n    __asm__ __volatile__(\n{_asm(body)}\n"
        f'        :: "r"(buf), "r"(iters) : "memory", "cc", {clob});\n}}'
    )


_MD_HEAD = r"""
/* generated by uarchre/kernels/memory.py: P2.5 memory-dependence probe */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
"""

_MD_FWD = {
    "riscv64": r"""/* store-to-load round trip: sd a0, 0(p); ld a0, 0(p) (dependent through memory) */
static void fwd(char *p, uint64_t n) {
    __asm__ __volatile__(
        ".option push\n\t.option norvc\n\t"
        "li a0, 1\n\t"
        "1:\n\t"
"""
    + '        "sd a0, 0(%0)\\n\\t" "ld a0, 0(%0)\\n\\t"\n' * 8
    + r"""        "addi %1, %1, -1\n\t" "bnez %1, 1b\n\t"
        ".option pop\n\t"
        : "+r"(p), "+r"(n) :: "memory", "a0");
}
""",
    "aarch64": r"""/* store-to-load round trip: str x9, [p]; ldr x9, [p] (dependent through memory) */
static void fwd(char *p, uint64_t n) {
    __asm__ __volatile__(
        "mov x9, #1\n\t" "cmp x9, %1\n\t"
        "1:\n\t"
"""
    + '        "str x9, [%0]\\n\\t" "ldr x9, [%0]\\n\\t"\n' * 8
    + r"""        "subs %1, %1, #1\n\t" "b.ne 1b\n\t"
        : "+r"(p), "+r"(n) :: "memory", "cc", "x9");
}
""",
}

_MD_FWD2_A64 = (
    r"""/* forced-sequential pair: str x1, [x1]; ldr x2, [x2], x1 = x2 = p and [p] = p: every load reads the
   store just before it, and its address comes from the load before */
static void fwd2(char *p, uint64_t n) {
    __asm__ __volatile__(
        "mov x1, %0\n\t" "mov x2, %0\n\t" "str x1, [x1]\n\t" "cmp x1, %1\n\t"
        "1:\n\t"
"""
    + '        "str x1, [x1]\\n\\t" "ldr x2, [x2]\\n\\t"\n' * 8
    + r"""        "subs %1, %1, #1\n\t" "b.ne 1b\n\t"
        : "+r"(p), "+r"(n) :: "memory", "cc", "x1", "x2");
}
"""
)
_MD_FWD_BRANCH = '    if (argc > 1 && !strcmp(argv[1], "fwd")) {\n'
_MD_FWD2_BRANCH = r"""    if (argc > 1 && !strcmp(argv[1], "fwd2")) {
        uint64_t n = strtoull(argv[2], 0, 0);
        int reps = atoi(argv[3]);
        fwd2(buf, n);
        for (int r = 0; r < reps; r++) {
            uint64_t t0 = cycles(); fwd2(buf, n); uint64_t t1 = cycles();
            printf("R fwd2 0 %d %.4f\n", r, (double)(t1 - t0) / (double)(n * 8));
        }
        return 0;
    }
"""

_MD_MAIN = r"""
int main(int argc, char **argv) {
    static char buf[16384] __attribute__((aligned(4096)));     /* slots < 6 KiB, + 8 KiB no-alias copy */
    memset(buf, 0, sizeof buf);
    if (argc > 1 && !strcmp(argv[1], "fwd")) {
        uint64_t n = strtoull(argv[2], 0, 0);
        int reps = atoi(argv[3]);
        fwd(buf, n);
        for (int r = 0; r < reps; r++) {
            uint64_t t0 = cycles(); fwd(buf, n); uint64_t t1 = cycles();
            printf("R fwd 0 %d %.4f\n", r, (double)(t1 - t0) / (double)(n * 8));
        }
        return 0;
    }
    uint64_t iters = strtoull(argv[2], 0, 0);
    int reps = atoi(argv[3]);
    for (int a = 4; a < argc; a++) {
        int n = atoi(argv[a]);
        for (unsigned k = 0; k < NMD; k++) {
            if (MD[k].n != n) continue;
            MD[k].fn(buf, iters);                      /* warm: train the predictor */
            double v[16];
            for (int r = 0; r < reps && r < 16; r++) {
                uint64_t t0 = cycles(); MD[k].fn(buf, iters); uint64_t t1 = cycles();
                v[r] = (double)(t1 - t0) / (double)(iters * n);
            }
            for (int r = 0; r < reps && r < 16; r++) printf("R memdep %d %d %.4f\n", n, r, v[r]);
            fflush(stdout);
        }
    }
    return 0;
}
"""


def memdep_source(ns, alias=True, isa="riscv64", counter="pmccntr"):
    """C source: `memdep <iters> <reps> N...` prints "R memdep N rep cycles_per_block",
    `fwd <n> <reps>` "R fwd 0 rep cycles_per_round_trip" (a store; load chain through one address),
    on aarch64 also `fwd2 <n> <reps>` "R fwd2 0 rep cycles_per_pair" (str x1, [x1]; ldr x2, [x2]).
    `counter` (aarch64 only): a key of aarch64.COUNTERS."""
    fwd, main = _MD_FWD.get(isa, ""), _MD_MAIN
    if isa == "riscv64":
        cyc = r"""static inline uint64_t cycles(void) { uint64_t c; __asm__ __volatile__("rdcycle %0" : "=r"(c) :: "memory"); return c; }
"""  # noqa: E501
        fns = [_memdep_fn(n, alias) for n in ns]
    elif isa == "aarch64":
        from ..backends.isa.aarch64 import COUNTERS

        cyc = COUNTERS[counter].lstrip("\n")
        fns = [_memdep_fn_a64(n, alias) for n in ns]
        fwd += _MD_FWD2_A64
        main = main.replace(_MD_FWD_BRANCH, _MD_FWD2_BRANCH + _MD_FWD_BRANCH)
    else:
        raise ValueError(isa)
    tag = "a" if alias else "n"
    table = ", ".join(f"{{{n}, md{tag}_{n}}}" for n in ns)
    return (
        _MD_HEAD
        + cyc
        + "\n".join(fns)
        + f"""
static const struct {{ int n; void (*fn)(char *, uint64_t); }} MD[] = {{ {table} }};
#define NMD (sizeof(MD) / sizeof(MD[0]))

"""
        + fwd
        + main
    )


def memdep_binary(ns, alias=True, isa="riscv64"):
    from ..backends.platform.gem5 import compile_c

    if max(ns) > MEMDEP_NMAX:
        raise ValueError(f"N up to {MEMDEP_NMAX}")
    return compile_c(memdep_source(ns, alias, isa), f"memdep_{'a' if alias else 'n'}", isa=isa)
