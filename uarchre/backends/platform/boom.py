def rtl_rob_entries(config):
    """ROB entries in the elaborated RTL: rob_val_<row> / rob_val_<bank>_<row> bits in
    the generated Rob.sv; None if the config has not been generated."""
    path = os.path.join(
        SIM_DIR, "generated-src", f"chipyard.harness.TestHarness.{config}", "gen-collateral", "Rob.sv"
    )
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        return len(set(re.findall(r"^\s*reg\s+(rob_val(?:_\d+)?_\d+);", fh.read(), re.M)))


BM_TEMPLATE = r"""
/* generated by uarch-re for BOOM bare metal (libgloss-htif), chains: {mode}: {name} */
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <unistd.h>

{cycle_counter}

#define ITERS      {iters}ULL
#define REPS       {reps}
#define PROBE_ADDS {probe_adds}ULL

static uint64_t cyc[REPS];
static char obuf[1024];
static int olen;
#define OUT(...) (olen += snprintf(obuf + olen, sizeof obuf - olen, __VA_ARGS__))

{chain_code}

/* counter ticks per dependent add, x 10000 */
static uint64_t clock_ratio_e4(uint64_t adds) {{
    uint64_t x = 0, n = adds / 64;
    if (!n) return 0;
    uint64_t t0 = cycles();
    __asm__ __volatile__ (
{probe_body}
        : "+r"(x), "+r"(n) :: "cc"
    );
    uint64_t t1 = cycles();
    __asm__ __volatile__("" :: "r"(x));
    return (t1 - t0) * 10000 / (adds / 64 * 64);
}}

int main(void) {{
    uint64_t t_main = cycles();
    void *a, *b;
    uint64_t t_build = cycles();
    chains_init(&a, &b);
    t_build = cycles() - t_build;
    uint64_t scratch[16] = {{0}};
    uint64_t pre = PROBE_ADDS ? clock_ratio_e4(PROBE_ADDS) : 0;
    for (int r = 0; r < REPS; r++) {{
        uint64_t n = ITERS;
        uint64_t t0 = cycles();
        __asm__ __volatile__ (
{asm_body}
            : "+r"(a), "+r"(b), "+r"(n)
            : "r"(scratch)
            : "memory", "cc"{clobbers}
        );
        cyc[r] = cycles() - t0;
        __asm__ __volatile__("" :: "r"(a), "r"(b));
    }}
    uint64_t post = PROBE_ADDS ? clock_ratio_e4(PROBE_ADDS) : 0;
    /* printed after the loop so the reps run back to back */
    if (PROBE_ADDS) OUT("clock_ratio_pre %lu.%04lu\n", (unsigned long)(pre / 10000), (unsigned long)(pre % 10000));
    uint64_t best = (uint64_t)-1;
    for (int r = 0; r < REPS; r++) {{
        uint64_t q = cyc[r] * 1000 / ITERS;
        OUT("rep %d cycles_per_iter %lu.%03lu\n", r, (unsigned long)(q / 1000), (unsigned long)(q % 1000));
        if (q < best) best = q;
    }}
    if (PROBE_ADDS) OUT("clock_ratio_post %lu.%04lu\n", (unsigned long)(post / 10000), (unsigned long)(post % 10000));
    OUT("chains {mode} nodes {nodes} slot_lines {slot_lines} build_cycles %lu main_entry_cycles %lu\n",
        (unsigned long)t_build, (unsigned long)t_main);
    OUT("cycles_per_iter %lu.%03lu\n", (unsigned long)(best / 1000), (unsigned long)(best % 1000));
    OUT("total_cycles %lu\n", (unsigned long)cycles());
    write(1, obuf, olen);
    return 0;
}}
"""  # noqa: E501

# chains as initialized data: the simulator's +loadmem writes them into DRAM before reset
PRELOAD_CODE = r"""
#define REGION_WORDS {region_words}
static uintptr_t chain_a[REGION_WORDS] __attribute__((section(".uarchre_chains"), aligned(4096))) = {{
{init_a}
}};
static uintptr_t chain_b[REGION_WORDS] __attribute__((section(".uarchre_chains"), aligned(4096))) = {{
{init_b}
}};

static void chains_init(void **a, void **b) {{
    *a = (void *)&chain_a[{start_a}];
    *b = (void *)&chain_b[{start_b}];
}}
"""

# chains built by the program at fixed DRAM addresses, optionally flushed from the L2
RUNTIME_CODE = r"""
#define LINE       {line}ULL
#define NODES      {nodes}u
#define SLOT_LINES {slot_lines}ULL
#define SEED       {seed}u
#define L2_FLUSH32 {flush32}ULL      /* InclusiveCache Flush32 register; 0 = no flush */

static uint32_t order[NODES];

static uint64_t xs(uint64_t *s) {{ *s ^= *s << 13; *s ^= *s >> 7; *s ^= *s << 17; return *s; }}

/* node i: slot i, at a pseudo-random line in [0, SLOT_LINES - 2] of the slot */
static uintptr_t node_addr(uintptr_t base, uint64_t i, uint64_t salt) {{
    uint64_t h = (i + 1) * 0x9E3779B97F4A7C15ULL ^ salt;
    h ^= h >> 29; h *= 0xBF58476D1CE4E5B9ULL; h ^= h >> 32;
    return base + (i * SLOT_LINES + h % (SLOT_LINES - 1)) * LINE;
}}

static void *build_chain(uintptr_t base, uint32_t seed, uint64_t *salt) {{
    uint64_t s = seed | 1;
    for (int k = 0; k < 8; k++) xs(&s);
    *salt = xs(&s);
    for (uint32_t i = 0; i < NODES; i++) order[i] = i;
    for (uint32_t i = NODES - 1; i > 0; i--) {{          /* Sattolo: one cycle */
        uint32_t j = xs(&s) % i;
        uint32_t t = order[i]; order[i] = order[j]; order[j] = t;
    }}
    for (uint32_t i = 0; i < NODES; i++)
        *(volatile uintptr_t *)node_addr(base, order[i], *salt) =
            node_addr(base, order[(i + 1) % NODES], *salt);
    return (void *)node_addr(base, order[0], *salt);
}}

/* write back and evict every node line from the L2 (and, inclusive, the L1) */
static void flush_chain(uintptr_t base, uint64_t salt) {{
    if (!L2_FLUSH32) return;
    for (uint32_t i = 0; i < NODES; i++)
        *(volatile uint32_t *)L2_FLUSH32 = (uint32_t)(node_addr(base, i, salt) >> 4);
    __asm__ __volatile__("fence" ::: "memory");
}}

static void chains_init(void **a, void **b) {{
    uint32_t salt = SEED * 0x9E3779B9u;
    uint64_t sa, sb;
    *a = build_chain({base_a}ULL, 0x1234 ^ salt, &sa);
    *b = build_chain({base_b}ULL, 0x5678 ^ salt, &sb);
    flush_chain({base_a}ULL, sa);
    flush_chain({base_b}ULL, sb);
}}
"""


def chain_layout(kernel, iters, reps, region_bytes=2 << 20, margin=64, line=64):
    """(nodes, slot_lines) per chain: reps x iters x depth visits never wrap, span >= region_bytes."""
    used = reps * iters * kernel.params.get("depth", 1)
    nodes = used + margin
    slot_lines = max(4, -(-region_bytes // line // nodes))  # ceil: span >= region_bytes
    if nodes * slot_lines * line > CHAIN_SPAN_MAX:
        raise ValueError(f"{kernel.name}: {nodes} nodes x {slot_lines} lines exceeds the chain span")
    return nodes, slot_lines


def _preload_init(arr, nodes, slot_lines, line, rng):
    """(C designated initializers for one sparse chain in `arr`, word index of the first node)."""
    wpl = line // 8
    words = [(i * slot_lines + rng.randrange(slot_lines - 1)) * wpl for i in range(nodes)]
    order = list(range(nodes))
    for i in range(nodes - 1, 0, -1):  # Sattolo: one cycle through all nodes
        j = rng.randrange(i)
        order[i], order[j] = order[j], order[i]
    init = ",\n".join(
        f"    [{words[order[i]]}] = (uintptr_t)&{arr}[{words[order[(i + 1) % nodes]]}]" for i in range(nodes)
    )
    return init, words[order[0]]


def emit_baremetal(
    kernel, em=None, *, iters=100, reps=3, probe_adds=None, seed=0, region_bytes=2 << 20, chain="preload"
):
    if chain not in CHAIN_MODES:
        raise ValueError(f"chain must be one of {CHAIN_MODES}")
    em = em or RISCV64()
    nodes, slot_lines = chain_layout(kernel, iters, reps, region_bytes, line=em.line)
    if chain == "preload":
        rng = random.Random(f"uarchre-boom-{seed}")
        init_a, start_a = _preload_init("chain_a", nodes, slot_lines, em.line, rng)
        init_b, start_b = _preload_init("chain_b", nodes, slot_lines, em.line, rng)
        code = PRELOAD_CODE.format(
            region_words=nodes * slot_lines * em.line // 8,
            init_a=init_a,
            init_b=init_b,
            start_a=start_a,
            start_b=start_b,
        )
    else:
        code = RUNTIME_CODE.format(
            line=em.line,
            nodes=nodes,
            slot_lines=slot_lines,
            seed=seed,
            flush32=hex(L2_FLUSH32) if chain == "flush" else "0",
            base_a=hex(CHAIN_BASE[0]),
            base_b=hex(CHAIN_BASE[1]),
        )
    return BM_TEMPLATE.format(
        name=kernel.name,
        mode=chain,
        cycle_counter=em.cycle_counter_c,
        chain_code=code,
        nodes=nodes,
        slot_lines=slot_lines,
        iters=iters,
        reps=reps,
        probe_adds=em.default_probe_adds if probe_adds is None else probe_adds,
        probe_body=_asm(["1:"] + [em.probe_add()] * 64 + list(em.probe_tail())),
        asm_body=_asm(em.lower(kernel)),
        clobbers="".join(f', "{c}"' for c in em.clobbers),
    )


def _build_dir():
    d = os.path.join(ROOT, "build", "boom")
    os.makedirs(d, exist_ok=True)
    return d


def compile_baremetal(src, name):
    """Compile a bare-metal C source against libgloss-htif; cached by content hash."""
    h = hashlib.md5((src + CC + " ".join(CFLAGS)).encode()).hexdigest()[:10]
    d = _build_dir()
    cpath, elf = os.path.join(d, f"{name}_{h}.c"), os.path.join(d, f"{name}_{h}.riscv")
    if not os.path.exists(elf):
        with open(cpath, "w") as fh:
            fh.write(src)
        tmp = f"{elf}.{os.getpid()}.{threading.get_ident()}"
        subprocess.run(["taskset", "-c", CPUS, CC, *CFLAGS, "-T", HTIF_LD, cpath, "-o", tmp], check=True)
        os.replace(tmp, elf)
    return elf


def run_sim(elf, config, max_cycles=20_000_000, timeout=7200, use_slot=True):
    """Run a bare-metal ELF on the Chipyard Verilator simulator (DRAMSim2, ELF preloaded).
    Returns (output, core cycles from reset to the end of main, or None if not printed)."""
    sim = sim_path(config)
    if not os.path.exists(sim):
        raise FileNotFoundError(f"{sim}: build it with validation/boom/build.sh {config}")
    cmd = [
        "taskset",
        "-c",
        CPUS,
        sim,
        "+permissive",
        "+dramsim",
        f"+dramsim_ini_dir={DRAMSIM_INI}",
        f"+max-cycles={max_cycles}",
        f"+loadmem={elf}",
        "+permissive-off",
        elf,
    ]
    env = {
        **os.environ,
        "LD_LIBRARY_PATH": os.path.join(RISCV, "lib") + ":" + os.environ.get("LD_LIBRARY_PATH", ""),
    }

    def go():
        return subprocess.run(
            cmd, capture_output=True, text=True, timeout=timeout, env=env, stdin=subprocess.DEVNULL
        )

    if use_slot:
        with slot():
            r = go()
    else:
        r = go()
    out = r.stdout + r.stderr
    # "*** PASSED ***" needs +verbose, which traces every instruction; success is a
    # clean exit, no FAILED, and the program's output
    m = re.search(r"^total_cycles (\d+)", out, re.M)
    if r.returncode != 0 or "*** FAILED ***" in out or not re.search(r"^cycles_per_iter ", out, re.M):
        raise RuntimeError(f"BOOM sim failed ({r.returncode}) for {elf} on {config}:\n{out[-3000:]}")
    return out, int(m.group(1)) if m else None


def run_boom_reps(
    kernel,
    config,
    *,
    iters=100,
    reps=3,
    seed=0,
    probe_adds=None,
    region_bytes=2 << 20,
    chain="preload",
    max_cycles=20_000_000,
):
    """Run a window-probe kernel once on BOOM RTL; RunResult with every inner rep.
    The simulator is deterministic per binary: vary `seed` for spread."""
    src = emit_baremetal(
        kernel,
        iters=iters,
        reps=reps,
        probe_adds=probe_adds,
        seed=seed,
        region_bytes=region_bytes,
        chain=chain,
    )
    elf = compile_baremetal(src, kernel.name + ("" if chain == "preload" else f"_{chain}"))
    out, _ = run_sim(elf, config, max_cycles=max_cycles)
    return parse_output(out)


def run_boom(kernel, config, **kw):
    """Minimum cycles/iter over the inner reps."""
    return run_boom_reps(kernel, config, **kw).best
