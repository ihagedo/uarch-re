"""BOOM RTL driver (P0.5): bare-metal window probe on Chipyard BOOM under Verilator.

Configured RTL parameters are ground truth (L2). The timed loop is the RISC-V emitter's lowering in a
bare-metal libgloss-htif harness (no argv or malloc; integer printf, as newlib-nano has no %f). Chains
are sparse (one node per SLOT_LINES-line slot, never in its last line) so the next-line prefetcher
cannot fetch a node; `chain=` picks how they reach DRAM cold: preload (ELF data via +loadmem, default),
flush (built, then evicted via Flush32) or cached (a control). Simulators: validation/boom/build.sh.
"""

